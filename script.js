/*Задача 1. JavaScript: поиск и фильтрация карточек
/Сценарий: на странице медиатеки пользователь ищет статьи по названию и выбирает категорию.

Что нужно сделать: написать функцию filterArticles(articles, query, category), которая возвращает подходящие статьи.

Требования:
- Поиск работает по части названия, без учёта регистра.
- Пробелы в начале и конце запроса игнорируются.
- Категория "Все" отключает фильтрацию по категории.
- Поиск и категория работают одновременно.
- Исходный массив не изменяется.

Задача 1: как рассуждать
Интервьюер: «Какие условия должна выполнить статья, чтобы попасть в результат?»
Раздели проверку на две независимые части:
1. Подходит ли название под поисковый запрос?
2. Подходит ли категория?
Затем подумай, каким логическим оператором их объединить: статья должна пройти обе проверки.
Интервьюер: «Что стоит сделать с запросом до перебора массива?»
Нормализовать его: убрать внешние пробелы и привести к одному регистру. Нет необходимости повторять эту работу для каждой статьи.
Интервьюер: «Какой метод массива подходит?»
Нужно оставить часть существующих элементов. Сравни назначение map и filter.
Дополнительный вопрос: почему пустой запрос должен показывать все статьи выбранной категории?

Пошаговый разбор
Поиск и фильтрация
1. Преобразуем запрос через trim() и toLowerCase().
2. Перебираем статьи через filter().
3. Название каждой статьи тоже приводим к нижнему регистру.
4. Проверяем вхождение запроса через includes().
5. Проверяем категорию: либо выбрано "Все", либо категория статьи совпадает с выбранной.
6. Возвращаем статью только при выполнении обеих проверок.

Пустая строка входит в любую строку: title.includes("") возвращает true. Поэтому пустой запрос естественным образом отключает поиск по названию.

Типичная ошибка: использовать || между проверкой названия и категории. Тогда статья попадёт в результат, даже если соответствует только одному условию.

Альтернатива: два последовательных filter() — сначала по названию, затем по категории. Так можно яснее разделить проверки, но понадобится два прохода. Для небольшого списка это обычно несущественно.
*/

// Исходные статьи: поиск проверяет title, фильтр категории — category.
const articles = [
  { id: 1, title: "Как работает ABC", category: "ABC" },
  { id: 2, title: "AI в программировании", category: "AI" },
  { id: 3, title: "Проверка ABC-модели", category: "ABC" },
  { id: 4, title: "Управление файлами", category: "ABC" },
];

// Основной вариант: один filter проверяет сразу оба условия.
function filterArticles(articles, query, category) {
  // Нормализуем запрос один раз перед перебором:
  // trim() убирает внешние пробелы, toLowerCase() — различия регистра.
  const normalizeQuery = query.trim().toLowerCase();

  // filter() возвращает новый массив подходящих статей,
  // не изменяя исходный массив и объекты внутри него.
  return articles.filter((article) => {
    // Приводим название к тому же регистру, что и запрос.
    // includes() возвращает true, если название содержит запрос.
    // Пустой запрос входит в любое название — поиск ничего не исключает.
    const matchesQuery = article.title.toLowerCase().includes(normalizeQuery);

    // || означает «ИЛИ»: подходит любая категория при выборе "Все",
    // иначе категория статьи должна точно совпасть с выбранной.
    const matchesCategory = category === "Все" || article.category === category;

    // && означает «И»: оставляем статью, только если
    // она одновременно подходит по названию и категории.
    return matchesQuery && matchesCategory;
  });
}

// Альтернатива с двумя фильтрами:
// сначала отбираем по названию, затем — по категории.
function filterArticlesAlternative(articles, query, category) {
  // Например, "  ABC  " превращается в "abc".
  // Исходная строка query не изменяется.
  const normalizedQuery = query.trim().toLowerCase();

  return (
    articles
      // Первый filter создаёт массив статей, подходящих по названию.
      // Сравниваем строки в одинаковом регистре.
      // Стрелочная функция без {} автоматически возвращает
      // результат includes(): true — оставить, false — исключить.
      .filter((article) =>
        article.title.toLowerCase().includes(normalizedQuery),
      )
      // Второй filter работает только со статьями из первого результата.
      // "Все" пропускает любую категорию; иначе требуется точное совпадение.
      // Поэтому итоговые статьи удовлетворяют ОБОИМ условиям.
      .filter((article) => category === "Все" || article.category === category)
  );
}

// Проверяем поиск с внешними пробелами и без ограничения категории.
// Результат: статьи с ID 1 и 3 — их названия содержат "abc".
// Статья 4 не попадает в результат: "ABC" есть в категории,
// но поиск по условиям задачи проверяет только название.
console.log(filterArticlesAlternative(articles, "  ABC  ", "Все"));
