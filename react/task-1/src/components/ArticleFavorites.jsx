// useState позволяет хранить данные между рендерами.
// Обновление состояния сообщает React, что интерфейс нужно обновить.
import { useState } from "react";

// Постоянный список статей хранится вне компонента:
// сами статьи в этой задаче не меняются.
// id нужен для определения статьи независимо от её позиции в массиве.
const articles = [
  { id: 1, title: "Как работает ABC", category: "ABC" },
  { id: 2, title: "AI в программировании", category: "AI" },
  { id: 3, title: "Проверка ABC-модели", category: "ABC" },
  { id: 4, title: "Управление файлами", category: "ABC" },
];

// Компонент описывает интерфейс списка статей и избранного.
// export default позволяет импортировать его в другом файле.
export default function ArticleFavorites() {
  // Храним только ID избранных статей, а не копии их объектов.
  // Изначально массив пустой — ни одна статья не выбрана.
  //
  // favoriteIds — состояние для текущего рендера.
  // setFavoriteIds — функция, через которую обновляем это состояние.
  const [favoriteIds, setFavoriteIds] = useState([]);

  // Получаем ID статьи, на кнопку которой нажал пользователь.
  // Одна функция отвечает и за добавление, и за удаление.
  function toggleFavorite(id) {
    // Новое состояние зависит от предыдущего, поэтому передаём функцию.
    // React передаст в currentIds актуальное предыдущее состояние
    // при обработке этого обновления.
    setFavoriteIds((currentIds) => {
      // includes() возвращает true, если этот ID уже есть в избранном.
      if (currentIds.includes(id)) {
        // Если статья выбрана — убираем её.
        // filter() создаёт новый массив со всеми ID, кроме нажатого.
        // !== проверяет строгое неравенство.
        // Остальные выбранные статьи сохраняются.
        return currentIds.filter((currentId) => currentId !== id);
      }

      // Если статья ещё не выбрана — добавляем её ID.
      // Spread копирует существующие ID в новый массив.
      // Исходный массив состояния не изменяется.
      //
      // Дубликата не будет: выше мы уже проверили наличие ID.
      return [...currentIds, id];
    });
  }

  // JSX описывает, что должно отображаться при текущем состоянии.
  return (
    <section className="favorites">
      <h1>Статьи</h1>

      {/* Счётчик вычисляем из массива, а не храним отдельно.
          Так количество всегда соответствует избранному. */}
      <p className="favorites-count" role="status">В избранном: {favoriteIds.length}</p>

      {/* При пустом избранном disabled получает true.
          При нажатии устанавливаем новый пустой массив:
          все статьи перестают быть избранными. */}
      <button
        type="button"
        disabled={favoriteIds.length === 0}
        onClick={() => setFavoriteIds([])}
      >
        Очистить избранное
      </button>

      <ul className="article-list">
        {/* map() преобразует каждую статью в JSX-элемент списка.
            Он подходит для отображения всех статей, а filter()
            использовался выше для удаления ID из избранного. */}
        {articles.map((article) => {
          // Для каждой статьи вычисляем, выбрана ли она сейчас.
          // Отдельное состояние isFavorite не нужно:
          // ответ уже содержится в favoriteIds.
          const isFavorite = favoriteIds.includes(article.id);

          // В callback с фигурными скобками нужен явный return,
          // чтобы map() получил JSX для этой статьи.
          return (
            // key помогает React сопоставлять элементы между рендерами.
            // Используем стабильный ID статьи.
            <li key={article.id} className="article-card">
              <h2>{article.title}</h2>

              {/* type="button" предотвращает отправку формы,
                  если компонент окажется внутри неё.

                  aria-pressed сообщает, выбрана ли кнопка.

                  В onClick передаём функцию, чтобы toggleFavorite()
                  вызвалась при нажатии с ID нужной статьи,
                  а не сразу во время рендера. */}
              <button
                type="button"
                aria-pressed={isFavorite}
                onClick={() => toggleFavorite(article.id)}
              >
                {/* Тернарный оператор выбирает подпись кнопки:
                    выбранная статья → предложение убрать,
                    невыбранная → предложение добавить. */}
                {isFavorite ? "Убрать из избранного" : "В избранное"}
              </button>
            </li>
          );
        })}
      </ul>
    </section>
  );
}
